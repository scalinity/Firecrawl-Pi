def Q(query, rel, ev, *, explicit=False, ver=None, si=None, cons=None, tags=(), nomatch=False, notes=""):
    return dict(query=query, rel=rel, ev=list(ev), explicit=explicit, ver=ver, si=si,
                cons=cons or {}, tags=list(tags), nomatch=nomatch, notes=notes)


def V(lib, version):
    return {"library": lib, "version": version}


def SI(doc="auto", libs=None, lang=None):
    out = {"documentation": doc}
    if libs:
        out["libraries"] = [({"name": n, "version": v} if v else {"name": n}) for n, v in libs]
    if lang:
        out["programmingLanguage"] = lang
    return out


def W(after, before, mode="strict_publication"):
    return {"publishedAfter": after, "publishedBefore": before, "dateMode": mode}


