def derive_tags(rec):
    tags = list(rec["tags"])
    add = []
    add.append("docs_positive" if rec["rel"] in DOC_POS else "docs_negative")
    if rec["rel"].startswith("ambiguous_"):
        add.append("docs_ambiguous")
    if rec["explicit"]:
        add.append("docs_explicit")
    if rec["ver"]:
        add.append("version_constraint")
    if rec["nomatch"]:
        add.append("no_match_expected")
    if "```" in rec["query"]:
        add.append("code_fence")
    if len(rec["query"]) > 128:
        add.append("long_query")
    cons = rec["cons"]
    if cons.get("publishedAfter") or cons.get("publishedBefore"):
        add.append("time_window")
    if cons.get("includeDomains") or cons.get("excludeDomains"):
        add.append("restricted_domain")
    out = []
    for t in add + tags:
        if t not in out:
            out.append(t)
    return out


